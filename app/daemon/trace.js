'use strict';
// F66 execution trace (design/46): an append-only, hash-chained audit log of
// what the agent did in each turn — model steps, tool calls with arguments,
// policy decisions and approvals, delivered artifacts with content hashes.
//
// Layout: <dir>/<sessionId>.jsonl, one record per line. Every record carries
// prev + hash where hash = sha256(prev + canonicalJSON(record without hash)),
// so trace.verify detects an edited, deleted or inserted line. The log lives
// beside the DAO (same file-layout ruling as F58): it is only ever appended to
// and is deleted with its session. Writes are best-effort: a trace failure is
// logged and never breaks the turn it describes.

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const GENESIS = '0'.repeat(64);
const DEFAULTS = { maxBytes: 20 * 1024 * 1024, argsChars: 2000, summaryChars: 500, textChars: 1000 };
const SECRET_SHAPES = [
  /\bsk-[A-Za-z0-9_-]{12,}/g, // OpenAI-style keys
  /\bBearer\s+[A-Za-z0-9._~+/=-]{12,}/g,
  /\bgh[pousr]_[A-Za-z0-9]{20,}/g, // GitHub tokens
  /\bxox[abprs]-[A-Za-z0-9-]{10,}/g, // Slack tokens
  /\bAKIA[0-9A-Z]{16}\b/g, // AWS access key id
  /\b\d{8,10}:[A-Za-z0-9_-]{30,}\b/g, // Telegram bot token
];

const sha256 = (s) => crypto.createHash('sha256').update(s).digest('hex');

// key-sorted JSON so the hash does not depend on property order
function canonical(value) {
  if (Array.isArray(value)) return '[' + value.map(canonical).join(',') + ']';
  if (value && typeof value === 'object') {
    return '{' + Object.keys(value).sort().filter((k) => value[k] !== undefined)
      .map((k) => JSON.stringify(k) + ':' + canonical(value[k])).join(',') + '}';
  }
  return JSON.stringify(value === undefined ? null : value);
}

function hashOf(record) {
  const { hash: _omit, ...body } = record;
  return sha256(record.prev + canonical(body));
}

function clip(text, max) {
  const s = String(text == null ? '' : text);
  return s.length > max ? { text: s.slice(0, max), truncated: true } : { text: s, truncated: false };
}

function fileFor(dir, sessionId) {
  const id = String(sessionId || '');
  // session ids are generated by the store; anything else is hashed so it
  // can never name a path outside the trace directory
  const safe = /^[A-Za-z0-9_-]{1,80}$/.test(id) ? id : 'h' + sha256(id).slice(0, 40);
  return path.join(dir, safe + '.jsonl');
}

/**
 * @param {{dir:string, enabled?:()=>boolean, secrets?:()=>string[], log?:Function, now?:()=>number, maxBytes?:number}} opts
 */
function createTraceStore(opts) {
  const dir = opts.dir;
  const enabled = opts.enabled || (() => true);
  const secrets = opts.secrets || (() => []);
  const log = opts.log || (() => {});
  const now = opts.now || Date.now;
  const maxBytes = opts.maxBytes || DEFAULTS.maxBytes;
  const heads = new Map(); // sessionId → {seq, prev, turn, size, limited}

  function redactString(s) {
    let out = String(s);
    for (const secret of secrets()) {
      if (typeof secret === 'string' && secret.length >= 8 && out.includes(secret)) out = out.split(secret).join('[REDACTED]');
    }
    for (const re of SECRET_SHAPES) out = out.replace(re, '[REDACTED]');
    return out;
  }
  function redact(value) {
    if (typeof value === 'string') return redactString(value);
    if (Array.isArray(value)) return value.map(redact);
    if (value && typeof value === 'object') {
      const o = {};
      for (const [k, v] of Object.entries(value)) o[k] = redact(v);
      return o;
    }
    return value;
  }

  function read(sessionId) {
    let raw;
    try { raw = fs.readFileSync(fileFor(dir, sessionId), 'utf8'); } catch (_) { return []; }
    const out = [];
    for (const line of raw.split('\n')) {
      if (!line.trim()) continue;
      try { out.push(JSON.parse(line)); } catch (_) { out.push({ kind: 'corrupt', raw: line.slice(0, 200) }); }
    }
    return out;
  }

  function head(sessionId) {
    let h = heads.get(sessionId);
    if (h) return h;
    const records = read(sessionId);
    const last = records.filter((r) => r.hash).at(-1);
    let size = 0;
    try { size = fs.statSync(fileFor(dir, sessionId)).size; } catch (_) {}
    h = { seq: last ? last.seq : 0, prev: last ? last.hash : GENESIS,
      turn: records.reduce((m, r) => Math.max(m, r.turn || 0), 0), size,
      limited: records.some((r) => r.kind === 'limit') };
    heads.set(sessionId, h);
    return h;
  }

  function write(sessionId, h, body) {
    const record = { seq: h.seq + 1, ts: now(), ...body, prev: h.prev };
    record.hash = hashOf(record);
    const line = JSON.stringify(record) + '\n';
    fs.mkdirSync(dir, { recursive: true });
    fs.appendFileSync(fileFor(dir, sessionId), line);
    h.seq = record.seq; h.prev = record.hash; h.size += Buffer.byteLength(line);
    return record;
  }

  /** Append one record. Never throws; returns the record or null. */
  function append(sessionId, body) {
    if (!sessionId || !enabled()) return null;
    try {
      const h = head(sessionId);
      if (h.limited) return null;
      const record = redact({ turn: h.turn, ...body });
      if (h.size + JSON.stringify(record).length > maxBytes) {
        h.limited = true;
        return write(sessionId, h, { turn: h.turn, kind: 'limit', note: 'trace size cap reached (' + maxBytes + ' bytes); later steps not recorded' });
      }
      return write(sessionId, h, record);
    } catch (e) {
      log('warn', 'trace', 'append failed (turn continues): ' + e.message);
      return null;
    }
  }

  /** Open a new turn and record its start. */
  function beginTurn(sessionId, body) {
    if (!sessionId || !enabled()) return null;
    try { head(sessionId).turn++; } catch (_) { return null; }
    return append(sessionId, { kind: 'turn_start', ...body });
  }

  function verify(sessionId) {
    const records = read(sessionId);
    let prev = GENESIS;
    for (let i = 0; i < records.length; i++) {
      const r = records[i];
      if (r.kind === 'corrupt' || r.prev !== prev || r.hash !== hashOf(r) || r.seq !== i + 1) {
        return { ok: false, count: records.length, brokenAt: i + 1 };
      }
      prev = r.hash;
    }
    return { ok: true, count: records.length };
  }

  function turnsOf(records) {
    const turns = new Map();
    for (const r of records) {
      if (!r.turn) continue;
      if (!turns.has(r.turn)) turns.set(r.turn, []);
      turns.get(r.turn).push(r);
    }
    return turns;
  }

  function summarize(turn, recs) {
    const start = recs.find((r) => r.kind === 'turn_start') || {};
    const end = recs.find((r) => r.kind === 'turn_end') || null;
    return {
      turn, startedAt: start.ts || recs[0].ts, endedAt: end ? end.ts : null,
      source: start.source || null, prompt: start.prompt || '', mode: start.mode || null, model: start.model || null,
      reason: end ? end.reason : null,
      steps: recs.filter((r) => r.kind === 'llm_step').length,
      tools: recs.filter((r) => r.kind === 'tool_call').length,
      artifacts: recs.filter((r) => r.kind === 'tool_result' && r.artifact).map((r) => r.artifact.path),
    };
  }

  function list(sessionId) {
    return [...turnsOf(read(sessionId))].map(([turn, recs]) => summarize(turn, recs));
  }

  function get(sessionId, turn) {
    const records = read(sessionId);
    return turn ? records.filter((r) => r.turn === Number(turn)) : records;
  }

  /** The most recent turn that delivered `target`. */
  function forArtifact(sessionId, target) {
    const records = read(sessionId);
    const hit = records.filter((r) => r.kind === 'tool_result' && r.artifact && r.artifact.path === target).at(-1);
    if (!hit) return { turn: null, records: [] };
    return { turn: hit.turn, records: records.filter((r) => r.turn === hit.turn) };
  }

  function exportReport(sessionId, { turn, format = 'md', title = '' } = {}) {
    const records = get(sessionId, turn);
    const check = verify(sessionId);
    const stamp = new Date(now()).toISOString().replace(/[:.]/g, '-').slice(0, 19);
    const base = 'myagent-trace-' + String(sessionId).slice(0, 12) + (turn ? '-turn' + turn : '') + '-' + stamp;
    if (format === 'json') {
      return { filename: base + '.json', content: JSON.stringify({ sessionId, title, turn: turn || null, verify: check, records }, null, 2) };
    }
    const lines = ['# MyAgent 执行轨迹审计报告', ''];
    lines.push('- 会话：' + (title || sessionId) + ' (`' + sessionId + '`)');
    lines.push('- 范围：' + (turn ? '第 ' + turn + ' 轮' : '全部轮次'));
    lines.push('- 哈希链：' + (check.ok ? '✓ 完整（' + check.count + ' 条记录）' : '✗ 自第 ' + check.brokenAt + ' 条起不一致'));
    lines.push('- 导出时间：' + new Date(now()).toISOString(), '');
    for (const [t, recs] of turnsOf(records)) {
      const s = summarize(t, recs);
      lines.push('## 第 ' + t + ' 轮', '');
      lines.push('- 来源：' + (s.source || '—') + '；模式：' + (s.mode || '—') + '；模型：' + (s.model || '—'));
      lines.push('- 开始：' + new Date(s.startedAt).toISOString() + (s.endedAt ? '；结束：' + new Date(s.endedAt).toISOString() + '（' + s.reason + '）' : '；未结束'));
      lines.push('- 指令：' + s.prompt.replace(/\s+/g, ' ').slice(0, 300), '');
      lines.push('| # | 时间 | 类型 | 内容 | 结果 |', '|---|---|---|---|---|');
      for (const r of recs) {
        const time = new Date(r.ts).toISOString().slice(11, 19);
        const cell = (x) => String(x == null ? '' : x).replace(/\|/g, '\\|').replace(/\s+/g, ' ').slice(0, 240);
        if (r.kind === 'llm_step') lines.push(`| ${r.seq} | ${time} | 模型调用 #${r.step} | ${r.toolCalls} 个工具调用 | ${r.ms}ms${r.tokens ? ' · ' + r.tokens + ' tokens' : ''} |`);
        else if (r.kind === 'tool_call') lines.push(`| ${r.seq} | ${time} | 工具 ${cell(r.name)} (${r.toolKind}) | ${cell(r.args)} | — |`);
        else if (r.kind === 'confirm') lines.push(`| ${r.seq} | ${time} | 人工确认 | ${cell(r.describe)} | ${r.outcome} |`);
        else if (r.kind === 'tool_result') {
          const art = r.artifact ? ' · 产物 `' + cell(r.artifact.path) + '` sha256=' + (r.artifact.sha256 || '—') : '';
          lines.push(`| ${r.seq} | ${time} | 结果 ${cell(r.name)} | ${cell(r.summary)}${art} | ${r.ok ? 'ok' : 'fail'} · ${r.policy} · ${r.ms}ms |`);
        } else if (r.kind === 'turn_end') lines.push(`| ${r.seq} | ${time} | 结束 | ${cell(r.reply)} | ${r.reason}${r.tokens ? ' · ' + r.tokens + ' tokens' : ''} |`);
        else if (r.kind === 'turn_start') lines.push(`| ${r.seq} | ${time} | 开始 | ${cell(r.prompt)} | ${r.source} |`);
        else lines.push(`| ${r.seq} | ${time} | ${cell(r.kind)} | ${cell(r.note || '')} | — |`);
      }
      lines.push('');
    }
    return { filename: base + '.md', content: lines.join('\n') };
  }

  function remove(sessionId) {
    heads.delete(sessionId);
    try { fs.rmSync(fileFor(dir, sessionId), { force: true }); } catch (_) {}
    return true;
  }

  function removeAll() {
    heads.clear();
    try { fs.rmSync(dir, { recursive: true, force: true }); } catch (_) {}
    return true;
  }

  return { append, beginTurn, read, list, get, forArtifact, verify, exportReport, remove, removeAll, clip, redact, _fileFor: (s) => fileFor(dir, s) };
}

/** sha256 + size of a local file, bounded; never throws. */
function hashFile(p, maxBytes = 50 * 1024 * 1024) {
  try {
    const st = fs.statSync(p);
    if (!st.isFile()) return { sha256: null, size: null, skipped: 'not_file' };
    if (st.size > maxBytes) return { sha256: null, size: st.size, skipped: 'too_large' };
    return { sha256: sha256(fs.readFileSync(p)), size: st.size };
  } catch (_) {
    return { sha256: null, size: null, skipped: 'missing' };
  }
}

module.exports = { createTraceStore, hashFile, canonical, clip, DEFAULTS, GENESIS };
